// Embeds the admin page into a module, then bundles both Workers with `wrangler deploy --dry-run`,
// so tests run the same code that a deploy would upload.
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const build = path.join(root, 'build');
const wrangler = path.join(root, 'node_modules/wrangler/bin/wrangler.js');
const pages = {
  '/': ['index.html', 'text/html; charset=utf-8'],
  '/app.js': ['app.js', 'text/javascript; charset=utf-8'],
  '/app.css': ['app.css', 'text/css; charset=utf-8']
};

await rm(build, { recursive: true, force: true });
await mkdir(build, { recursive: true });
const ui = {};
for (const [route, [file, type]] of Object.entries(pages)) ui[route] = { type, body: await readFile(path.join(root, 'src/admin-ui', file), 'utf8') };
await writeFile(path.join(build, 'admin-ui.js'), '// Generated by scripts/build.mjs from src/admin-ui.\nexport default ' + JSON.stringify(ui, null, 2) + ';\n');

for (const name of ['public', 'admin']) {
  const result = spawnSync(process.execPath, [wrangler, 'deploy', '--dry-run', '--outdir', path.join(build, name), '--config', 'wrangler.' + name + '.jsonc'], {
    cwd: root, encoding: 'utf8', env: { ...process.env, WRANGLER_SEND_METRICS: 'false' }
  });
  if (result.status !== 0) {
    process.stderr.write(result.stdout + result.stderr);
    throw new Error('Bundling the ' + name + ' Worker failed.');
  }
}
console.log('Built admin page module and Worker bundles in build/.');
